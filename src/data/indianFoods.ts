export function computePlateTotals(entries: { foodId: string; quantity: number }[]) {
  let calories = 0;
  let protein = 0;
  let carbs = 0;
  let fat = 0;
  let fibre = 0;
  let cautionCount = 0;

  for (const entry of entries) {
    const food = INDIAN_FOODS.find((f) => f.id === entry.foodId);
    if (!food) continue;
    calories += food.calories * entry.quantity;
    protein += food.protein * entry.quantity;
    carbs += food.carbs * entry.quantity;
    fat += food.fat * entry.quantity;
    fibre += food.fibre * entry.quantity;
    if (food.tags.includes('caution')) {
      cautionCount += entry.quantity;
    }
  }

  return {
    calories: Math.round(calories),
    protein: Number(protein.toFixed(1)),
    carbs: Number(carbs.toFixed(1)),
    fat: Number(fat.toFixed(1)),
    fibre: Number(fibre.toFixed(1)),
    cautionCount,
  };
}
